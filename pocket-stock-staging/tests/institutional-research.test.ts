test('large three-file source: isolated drafts, idempotency, conflict and review-bound publication', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'institutional-workflow-'));
    process.env.ADMIN_MASTER_SECRET = 'disposable-institutional-test';
    process.env.POCKETSTOCKS_DATA_DIR = dir;
    process.env.POCKETSTOCKS_LOCAL_ORIGIN = 'http://localhost:5173';
    const { db } = await import('../local/sdk.ts');
    const { makeInstitutionalRoutes } = await import('../backend/institutional-research.ts');
    const { makeEtfMarkdownRoutes } = await import('../backend/etf-markdown.ts');
    const helpers = { requireAdmin: async (e: any) => e.author ? { id: 'test' } : null, isSameOriginMutation: (e: any) => e.trusted };
    const routes = makeInstitutionalRoutes(helpers), etf = makeEtfMarkdownRoutes(helpers);
    const call = async (action: string, body: any = {}, author = true, trusted = true) => { const r = await routes['POST /api/admin/institutional-research/' + action][0]({ body, event: { author, trusted }, params: {}, query: {} } as any); return { status: r!.statusCode, data: JSON.parse(r!.body) }; };
    const publicRead = async () => { const r = await routes['GET /api/institutional/reports/:id'][0]({ params: { id: 'qa-institutional-report' }, query: {} } as any); return { status: r!.statusCode, data: JSON.parse(r!.body) }; };
    const publicList=async(query:any={})=>{const r=await routes['GET /api/institutional/reports'][0]({query} as any);return {status:r!.statusCode,data:JSON.parse(r!.body)};};
    try {
        const d = fixture();
        d.internal_padding = 'large source '.repeat(250000);
        const raw = JSON.stringify(d);
        const cover = { filename: 'cover.jpg', contentBase64: readFileSync(new URL('./fixtures/institutional-cover.jpg', import.meta.url)).toString('base64') };
        const html = '<html><script>fetch("./data.json")</script></html>';
        const input = { rawSource: raw, reportHtml: html, cover, baseRevision: 0, requestId: 'institutional-save-001' };
        assert.equal((await call('validate', input, false)).status, 401);
        assert.equal((await call('validate', input, true, false)).status, 403);
        assert.equal((await call('validate', { ...input, cover: undefined })).status, 400);
        assert.equal((await call('validate', { ...input, reportHtml: undefined })).status, 400);
        const saved = await call('save', input);
        assert.equal(saved.status, 200, JSON.stringify(saved.data));
        let entry = saved.data.entry;
        assert.equal(entry.revision, 1);
        assert.equal(entry.draft.rawJson, raw);
        assert.equal(entry.draft.companionHtml, html);
        assert.equal(entry.publishedVersion, 0);
        assert.equal((await publicRead()).status, 404);
        assert.deepEqual((await publicList()).data.items, []);
        assert.equal((await call('save', input)).data.entry.revision, 1);
        const etfList = await etf['POST /api/admin/etf-markdown/list'][0]({ body: {}, event: { author: true, trusted: true } } as any);
        assert.deepEqual(JSON.parse(etfList!.body).items, []);
        assert.equal((await call('publish', { id: entry.id, baseRevision: 1, expectedPublishedVersion: 0, reviewHash: 'wrong', reviewed: true, requestId: 'institutional-pub-reject' })).status, 409);
        entry = (await call('review', { id: entry.id, baseRevision: 1, sourceHash: entry.draft.sourceHash, requestId: 'institutional-review-001' })).data.entry;
        assert.ok(entry.reviewHash);
        entry = (await call('save', { ...input, reportHtml: html + '<!-- revised -->', baseRevision: 1, requestId: 'institutional-save-002' })).data.entry;
        assert.equal(entry.revision, 2);
        assert.equal(entry.reviewHash, null);
        assert.equal((await call('save', { ...input, requestId: 'institutional-stale-001' })).status, 409);
        entry = (await call('review', { id: entry.id, baseRevision: 2, sourceHash: entry.draft.sourceHash, requestId: 'institutional-review-002' })).data.entry;
        const published = await call('publish', { id: entry.id, baseRevision: 2, expectedPublishedVersion: 0, reviewHash: entry.reviewHash, reviewed: true, requestId: 'institutional-publish-001' });
        assert.equal(published.status, 200);
        const read = await publicRead();
        assert.equal(read.status, 200);
        assert.equal(read.data.report.companionHtml, html + '<!-- revised -->');
        assert.equal(read.data.report.rawJson, raw);
        const coverRead=await routes['GET /api/institutional/reports/:id/cover'][0]({params:{id:entry.id},query:{version:'1',sha256:published.data.entry.cover.sha256}} as any);assert.equal(coverRead!.statusCode,200);
        const listed=await publicList();assert.equal(listed.status,200);assert.equal(listed.data.items.length,1);assert.equal(listed.data.items[0].version,1);assert.equal(listed.data.items[0].cover.sha256,published.data.entry.cover.sha256);assert.equal(listed.data.items[0].manifest,undefined);
        assert.equal((await publicList({nextToken:'x'.repeat(4097)})).status,400);
        const draft=fixture();draft.metadata.article_title='Unpublished changed title';
        entry=(await call('save',{...input,rawSource:JSON.stringify(draft),baseRevision:2,requestId:'institutional-private-003'})).data.entry;
        assert.notEqual((await publicList()).data.items[0].title,entry.draft.title);
        entry=(await call('visibility',{id:entry.id,baseRevision:3,expectedPublishedVersion:1,expectedUpdatedAt:entry.updatedAt,archived:true,requestId:'institutional-hide-001'})).data.entry;
        assert.deepEqual((await publicList()).data.items,[]);assert.equal((await publicRead()).status,404);
        entry=(await call('visibility',{id:entry.id,baseRevision:3,expectedPublishedVersion:1,expectedUpdatedAt:entry.updatedAt,archived:false,requestId:'institutional-show-001'})).data.entry;
        assert.equal((await publicList()).data.items[0].version,1);assert.equal((await publicRead()).data.report.rawJson,raw);

    }
    finally {
        db.close();
        rmSync(dir, { recursive: true, force: true });
    }
});
